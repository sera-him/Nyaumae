// Generate a "catch-all" frequency corpus from prose-bearing component/page
// sources. The hand-built fullSearchIndex only indexes structured data modules,
// so Chinese/English text written inline in components (game rules, NCTB task
// prompts, descriptions) was never counted. This script extracts every string
// literal from those source files and emits per-file documents that fullSearchIndex
// imports. The engine's global segment de-duplication means any overlap with the
// already-indexed data is counted only once.
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const SRC = 'E:/app/src';
const OUT = 'E:/app/src/data/generated/frequencyCorpus.ts';

// Directories that hold rendered prose but are NOT already structured-indexed.
const SCAN_DIRS = [
  'sections',
  'pages',
  'components',
  'nctb/interactive',
];
// Skip pure code / mapping tables / generated files.
const SKIP_PATH = /(node_modules|lib[\\/]translations|generated[\\/]|\.test\.|__tests__)/;
const CJK = /[㐀-䶿一-鿿豈-﫿]/;
// English prose: at least 3 ASCII-letter words and no CJK.
const EN_PROSE = /^[A-Za-z0-9][A-Za-z0-9 ,.;:!?'"()/&%#+\-–—\n]{8,}$/;

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) { yield* walk(p); continue; }
    if (/\.(ts|tsx)$/.test(p) && !SKIP_PATH.test(p)) yield p;
  }
}

// Pull every '...', "...", `...` literal out of source, honoring escapes.
function extractLiterals(source) {
  const out = [];
  let i = 0;
  const n = source.length;
  while (i < n) {
    const ch = source[i];
    if (ch === "'" || ch === '"' || ch === '`') {
      const quote = ch;
      let j = i + 1;
      let buf = '';
      while (j < n) {
        const c = source[j];
        if (c === '\\') { buf += source[j + 1] ?? ''; j += 2; continue; }
        if (c === quote) break;
        if (quote === '`' && c === '$' && source[j + 1] === '{') {
          // skip interpolation, keep a space so surrounding text stays separate
          let depth = 1; j += 2;
          while (j < n && depth > 0) {
            if (source[j] === '{') depth++;
            else if (source[j] === '}') depth--;
            j++;
          }
          buf += ' ';
          continue;
        }
        buf += c;
        j++;
      }
      out.push(buf);
      i = j + 1;
    } else {
      i++;
    }
  }
  return out;
}

function clean(s) {
  return s.replace(/\s+/g, ' ').trim();
}

const zhDocs = [];
const enDocs = [];

for (const dir of SCAN_DIRS) {
  const root = join(SRC, dir);
  let files;
  try { files = [...walk(root)]; } catch { continue; }
  for (const file of files) {
    const rel = relative(SRC, file).replace(/\\/g, '/');
    const source = readFileSync(file, 'utf8');
    const lits = extractLiterals(source).map(clean).filter(Boolean);
    const zhSegs = [...new Set(lits.filter((s) => CJK.test(s)))];
    const enSegs = [...new Set(lits.filter((s) => !CJK.test(s) && EN_PROSE.test(s) && /[A-Za-z]/.test(s) && (s.match(/[A-Za-z]+/g)?.length ?? 0) >= 3))];
    if (zhSegs.length) {
      zhDocs.push({ id: `corpus_${rel}`, title: rel, content: zhSegs.join(' '), href: '#', category: '组件文案', segments: zhSegs });
    }
    if (enSegs.length) {
      enDocs.push({ id: `corpus_${rel}`, title: rel, content: enSegs.join(' '), href: '#', category: 'component copy', segments: enSegs });
    }
  }
}

const ts = `// AUTO-GENERATED by scripts/generate-frequency-corpus.mjs — do not edit by hand.
// Catch-all prose from component/page/interactive sources that the structured
// search index does not cover. The engine de-duplicates overlapping segments.

export interface CorpusDoc {
  id: string;
  title: string;
  content: string;
  href: string;
  category: string;
  segments: string[];
}

export const frequencyCorpusZh: CorpusDoc[] = ${JSON.stringify(zhDocs, null, 2)};

export const frequencyCorpusEn: CorpusDoc[] = ${JSON.stringify(enDocs, null, 2)};
`;

mkdirSync('E:/app/src/data/generated', { recursive: true });
writeFileSync(OUT, ts, 'utf8');
console.log(`zh docs: ${zhDocs.length}, en docs: ${enDocs.length}`);
console.log(`zh segments: ${zhDocs.reduce((a, d) => a + d.segments.length, 0)}, en segments: ${enDocs.reduce((a, d) => a + d.segments.length, 0)}`);
console.log('wrote', OUT);
